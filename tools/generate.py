# ---------------------------------------------------------------- helpers

def load(path: Path):
    with path.open(encoding="utf-8") as f:
        return json.load(f)


def eval_formula(text, x: int) -> int:
    """A skill number at level x: whole numbers, x, + - * / (rounding down) and parentheses."""
    node = ast.parse(str(text).replace("/", "//"), mode="eval")

    def ev(n):
        if isinstance(n, ast.Expression):
            return ev(n.body)
        if isinstance(n, ast.Constant) and isinstance(n.value, int):
            return n.value
        if isinstance(n, ast.Name) and n.id == "x":
            return x
        if isinstance(n, ast.UnaryOp) and isinstance(n.op, ast.USub):
            return -ev(n.operand)
        if isinstance(n, ast.BinOp):
            a, b = ev(n.left), ev(n.right)
            if isinstance(n.op, ast.Add):
                return a + b
            if isinstance(n.op, ast.Sub):
                return a - b
            if isinstance(n.op, ast.Mult):
                return a * b
            if isinstance(n.op, ast.FloorDiv):
                q = abs(a) // abs(b)  # C++ division truncates toward zero
                return q if (a >= 0) == (b >= 0) else -q
        raise ValueError(f"not a skill formula: {text!r}")

    return ev(node)


def num(n) -> str:
    if isinstance(n, float) and not n.is_integer():
        return f"{n:g}"
    return f"{int(n):,}"


def cell(text) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def table(headers, rows) -> str:
    if not rows:
        return ""
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(cell(c) for c in row) + " |" for row in rows]
    return "\n".join(out) + "\n"


def stats_text(stats: dict, sign=True) -> str:
    parts = []
    for k, v in stats.items():
        label = STAT_NAMES.get(k, k)
        parts.append(f"{label} {'+' if sign and isinstance(v, (int, float)) and v >= 0 else ''}{v}")
    return ", ".join(parts)


def seconds(ms) -> str:
    return f"{ms / 1000:g} s"


def anchor(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


class Wiki:
    def __init__(self, game: Path):
        self.game = game
        c = game / "content"
        self.c = c
        self.items = load(c / "items.json")
        self.rarities = load(c / "rarities.json")
        self.weapons = load(c / "weapons.json")
        self.statuses = load(c / "statuses.json")
        self.accomplishments = load(c / "accomplishments.json")
        self.ranks = load(c / "standing" / "ranks.json")
        self.exp = load(c / "stats" / "exp.json")

        job_list = load(c / "jobs" / "jobs.json")
        self.job_order = job_list["jobs"]
        self.jobs = {j: load(c / "jobs" / f"{j}.json") for j in self.job_order}

        # skill book file -> {skill id: skill}; skill id -> book
        self.books = {p.stem: load(p) for p in sorted((c / "skills").glob("*.json"))}
        self.skill_book = {sid: book for book, skills in self.books.items() for sid in skills}
        self.skills = {sid: s for skills in self.books.values() for sid, s in skills.items()}

        self.mobs = {p.stem: load(p) for p in sorted((c / "mobs").glob("*.json"))
                     if p.stem not in ("modifiers", "spawning")}
        self.modifiers = load(c / "mobs" / "modifiers.json")
        self.spawning = load(c / "mobs" / "spawning.json")
        self.drops = {p.stem: load(p) for p in sorted((c / "drops").glob("*.json"))}

        self.boss_order = load(c / "bosses" / "bosses.json")["bosses"]
        self.bosses = {b: load(c / "bosses" / f"{b}.json") for b in self.boss_order}

        self.npcs = {p.stem: load(p) for p in sorted((c / "npcs").glob("*.json"))}
        self.quest_order = load(c / "quests" / "quests.json")["quests"]
        self.quests = {q: load(c / "quests" / f"{q}.json") for q in self.quest_order}
        self.shops = {p.stem: load(p) for p in sorted((c / "shops").glob("*.json"))}

        self.maps = {}
        self.map_paths = {}
        for p in sorted((c / "maps").rglob("*.json")):
            self.maps[p.stem] = load(p)
            self.map_paths[p.stem] = p.relative_to(c).as_posix()
        self.regions = load(c / "world" / "regions.json")
        for rid, r in self.regions.items():  # newer content lists a region's maps only on the maps themselves
            r.setdefault("maps", sorted(
                (m for m, plan in self.maps.items() if plan.get("region") == rid),
                key=lambda m: (self.maps[m]["purpose"] != "town", self.maps[m].get("difficulty") or 0, self.maps[m]["name"])))
        self.discoveries = load(c / "world" / "discoveries.json")
        self.taxis = load(c / "world" / "taxis.json")

        self.professions = load(c / "lifeskills" / "professions.json")
        self.nodes = load(c / "lifeskills" / "nodes.json")
        self.recipes = {p.stem: load(p) for p in sorted((c / "lifeskills" / "recipes").glob("*.json"))}

        self.run_order = load(c / "runs" / "runs.json")["runs"]
        self.runs = {r: load(c / "runs" / f"{r}.json") for r in self.run_order}

        self.index()

    # ------------------------------------------------------------ cross-references

    def index(self):
        self.drop_users = defaultdict(list)       # drop table -> links of what uses it
        for mid, m in self.mobs.items():
            if m.get("drops"):
                self.drop_users[m["drops"]].append(self.mob(mid))
        for bid, b in self.bosses.items():
            for mode in b["modes"]:
                table_id = mode.get("boss", {}).get("drops")
                if table_id:
                    self.drop_users[table_id].append(f"{self.boss(bid)} ({mode['name']})")

        self.item_sources = defaultdict(list)     # item -> source lines
        self.item_uses = defaultdict(list)        # item -> use lines
        for table_id, t in self.drops.items():
            users = ", ".join(dict.fromkeys(self.drop_users.get(table_id, []))) or f"drop table `{table_id}`"
            for row in t.get("items", []):
                count = row.get("count")
                count_text = f" x{count[0]}-{count[1]}" if isinstance(count, list) else (f" x{count}" if count else "")
                self.item_sources[row["item"]].append(f"Dropped by {users} ({row['chance']:g}%{count_text})")

        self.shop_npc = {}
        for nid, n in self.npcs.items():
            if n.get("shop"):
                self.shop_npc[n["shop"]] = nid
        for sid, s in self.shops.items():
            for iid in s["items"]:
                self.item_sources[iid].append(f"Sold at {self.shop(sid)} for {num(self.items[iid]['price'] * s.get('markup', 2))} mesos")

        for prof, recipes in self.recipes.items():
            for rid, r in recipes.items():
                out = r["output"]["item"]
                self.item_sources[out].append(f"Made with {self.profession(prof)} (level {r['level']})")
                for i in r["inputs"]:
                    self.item_uses[i["item"]].append(f"{self.item(out)} ({self.profession(prof)}, x{i['count']})")

        for nid, n in self.nodes.items():
            self.item_sources[n["item"]].append(f"Gathered from {n['name']} ({self.profession(n['profession'])} level {n['level']})")

        for qid, q in self.quests.items():
            for key in ("rewards", "firstRewards"):
                for i in (q.get(key) or {}).get("items", []):
                    self.item_sources[i["item"]].append(f"Reward from {self.quest(qid)}")
            for o in q.get("objectives") or []:
                if o.get("item") and o["kind"] in ("collect", "deliver"):
                    self.item_uses[o["item"]].append(f"{self.quest(qid)} (bring {o['count']})")
            for action in q.get("onAccept", []):
                parts = action.split()
                if parts[:2] == ["give", "item"]:
                    self.item_sources[parts[2]].append(f"Given when you accept {self.quest(qid)}")

        for rid, r in self.runs.items():
            for mode in r.get("modes", []):
                for key in ("firstRewards", "rewards"):
                    for i in (mode.get(key) or {}).get("items", []):
                        self.item_sources[i["item"]].append(f"Reward from {self.run(rid)}")

        for jid, j in self.jobs.items():
            for i in j.get("advanceBonus", {}).get("items", []):
                self.item_sources[i["item"]].append(f"Given on becoming a {self.job(jid)}")

        # where monsters and NPCs appear
        self.mob_maps = defaultdict(list)
        self.npc_maps = defaultdict(list)
        self.node_maps = defaultdict(list)
        for map_id, m in self.maps.items():
            for s in m.get("spawns", []):
                if map_id not in self.mob_maps[s["mob"]]:
                    self.mob_maps[s["mob"]].append(map_id)
            for a in m.get("actors", []):
                if a["name"] in self.npcs and map_id not in self.npc_maps[a["name"]]:
                    self.npc_maps[a["name"]].append(map_id)
            for n in m.get("nodes", []):
                if map_id not in self.node_maps[n["node"]]:
                    self.node_maps[n["node"]].append(map_id)

        # quests by NPC; skills by how they are gained
        self.npc_quests = defaultdict(list)
        for qid, q in self.quests.items():
            for role in ("giver", "turnIn"):
                if q.get(role) and qid not in self.npc_quests[q[role]]:
                    self.npc_quests[q[role]].append(qid)

        self.skill_sources = defaultdict(list)
        for aid, a in self.accomplishments.items():
            if a["reward"].get("passive"):
                self.skill_sources[a["reward"]["passive"]].append(f"Accomplishment: {a['name']} ({a['description']})")
        for rid, r in self.regions.items():
            for m in r.get("mastery", []):
                for s in m.get("reward", {}).get("skills", []):
                    self.skill_sources[s["skill"]].append(f"{r['name']} mastery: {m['name']} ({m['discoveries']} discoveries)")
        for qid, q in self.quests.items():
            for s in (q.get("rewards") or {}).get("skills", []):
                self.skill_sources[s["skill"]].append(f"Quest: {self.quest(qid)}")
        self.job_quest = {}
        for qid, q in self.quests.items():
            for action in q.get("onComplete", []):
                parts = action.split()
                if parts[0] == "job":
                    self.job_quest[parts[1]] = qid

    # ------------------------------------------------------------ links (all pages sit one level below docs/)

    def item(self, iid):
        return f"[{self.items[iid]['name']}](../items/{iid}.md)" if iid in self.items else f"`{iid}`"

    def mob(self, mid):
        return f"[{self.mobs[mid]['name']}](../monsters/{mid}.md)" if mid in self.mobs else f"`{mid}`"

    def boss(self, bid):
        return f"[{self.bosses[bid]['name']}](../bosses/{bid}.md)"

    def npc(self, nid):
        return f"[{self.npcs[nid]['name']}](../npcs/{nid}.md)" if nid in self.npcs else f"`{nid}`"

    def quest(self, qid):
        return f"[{self.quests[qid]['title']}](../quests/{qid}.md)" if qid in self.quests else f"`{qid}`"

    def shop(self, sid):
        return f"[{self.shops[sid]['name']}](../shops/{sid}.md)"

    def map(self, mid):
        mid = mid.split("/")[0]
        return f"[{self.maps[mid]['name']}](../maps/{mid}.md)" if mid in self.maps else f"`{mid}`"

    def job(self, jid):
        return f"[{self.jobs[jid]['name']}](../jobs/{jid}.md)" if jid in self.jobs else f"`{jid}`"

    def skill(self, sid):
        if sid not in self.skills:
            return f"`{sid}`"
        return f"[{self.skills[sid]['name']}](../skills/{self.skill_book[sid]}.md#{anchor(sid)})"

    def profession(self, pid):
        for p in self.professions["professions"]:
            if p["id"] == pid:
                return f"[{p['name']}](../professions/{pid}.md)"
        return f"`{pid}`"

    def run(self, rid):
        return f"[{self.runs[rid]['name']}](../runs/{rid}.md)"

    def region(self, rid):
        return f"[{self.regions[rid]['name']}](../world/index.md#{anchor(rid)})" if rid in self.regions else f"`{rid}`"

    def town(self, tid):
        return self.regions[tid]["name"] if tid in self.regions else tid.replace("_", " ").title()

    # ------------------------------------------------------------ game text

    def text(self, s: str) -> str:
        """The game's text markup as Markdown."""
        def ref(m):
            kind, ident = m.group(1), m.group(2)
            return {"item": self.item, "mob": self.mob, "npc": self.npc, "map": self.map}.get(
                kind, lambda i: f"`{i}`")(ident) if kind != "count" else "(how many you carry)"
        s = re.sub(r"\{(item|mob|npc|map|count):([a-zA-Z0-9_.]+)\}", ref, s)
        s = s.replace("{player}", "*Player*").replace("{number}", "*N*")
        s = re.sub(r"\{(red|blue|green|bold)\}", "**", s)
        return s.replace("{/}", "**")

    def rewards(self, r: dict | None) -> list[str]:
        if not r:
            return []
        out = []
        if r.get("exp"):
            out.append(f"{num(r['exp'])} EXP")
        if r.get("meso"):
            out.append(f"{num(r['meso'])} mesos")
        for i in r.get("items", []):
            out.append(f"{self.item(i['item'])} x{i['count']}")
        for s in r.get("skills", []):
            out.append(f"Skill: {self.skill(s['skill'])}")
        for rec in r.get("recipes", []):
            out.append(f"Recipe: {self.recipe_name(rec)}")
        for st in r.get("standing", []):
            who = self.npc(st["npc"]) if "npc" in st else self.town(st["town"])
            out.append(f"+{st['points']} standing with {who}")
        for u in r.get("unlock", []):
            out.append(f"Unlocks `{u}`")
        for f in r.get("flags", []):
            out.append(f"Sets `{f}`")
        return out

    def recipe_name(self, rid):
        for prof, recipes in self.recipes.items():
            if rid in recipes:
                return f"{self.item(recipes[rid]['output']['item'])} ({self.profession(prof)})"
        return f"`{rid}`"

    # ------------------------------------------------------------ writing

    def write(self, rel: str, body: str):
        path = DOCS / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(HEADER + body.rstrip() + "\n", encoding="utf-8", newline="\n")

    def generate(self):
        for s in SECTIONS:
            shutil.rmtree(DOCS / s, ignore_errors=True)
        self.nav = {}
        self.gen_items()
        self.gen_skills()
        self.gen_jobs()
        self.gen_monsters()
        self.gen_bosses()
        self.gen_npcs()
        self.gen_quests()
        self.gen_shops()
        self.gen_world()
        self.gen_maps()
        self.gen_professions()
        self.gen_runs()
        self.gen_systems()
        self.write_nav()

    # ------------------------------------------------------------ items

    def gen_items(self):
        by_kind = defaultdict(list)
        for iid, it in self.items.items():
            by_kind[it["kind"]].append(iid)
            self.write(f"items/{iid}.md", self.item_page(iid, it))

        body = ["# Items\n", f"Wonder Kingdom has {len(self.items)} items. Prices are what a shop pays you; shops sell for more.\n"]
        rarity = ", ".join(r["name"] for r in self.rarities.values())
        body.append(f"Rarities, from lowest to highest: {rarity}.\n")
        for kind in KIND_NAMES:
            ids = by_kind.get(kind, [])
            if not ids:
                continue
            body.append(f"## {KIND_NAMES[kind]}\n")
            if kind == "equipment":
                by_slot = defaultdict(list)
                for iid in ids:
                    by_slot[self.items[iid]["slot"]].append(iid)
                for slot in SLOT_NAMES:
                    if slot not in by_slot:
                        continue
                    body.append(f"### {SLOT_NAMES[slot]}\n")
                    rows = sorted(by_slot[slot], key=lambda i: (self.items[i].get("requires", {}).get("level", 0), self.items[i]["name"]))
                    body.append(table(["Item", "Level", "Stats", "Slots", "Rarity"], [
                        [self.item(i), self.items[i].get("requires", {}).get("level", "-"),
                         stats_text(self.items[i].get("stats", {})), self.items[i].get("upgradeSlots", "-"),
                         self.rarities.get(self.items[i].get("rarity", "common"), {}).get("name", "")]
                        for i in rows]))
            else:
                body.append(table(["Item", "Price", "Description"], [
                    [self.item(i), num(self.items[i]["price"]), self.text(self.items[i]["description"])]
                    for i in sorted(ids, key=lambda i: self.items[i]["name"])]))
        self.write("items/index.md", "\n".join(body))
        self.nav["Items"] = "items/index.md"

    def item_page(self, iid, it):
        b = [f"# {it['name']}\n", f"*{self.text(it['description'])}*\n"]
        facts = [["Type", KIND_NAMES.get(it["kind"], it["kind"]).removesuffix("s")]]
        if it.get("rarity"):
            facts.append(["Rarity", self.rarities[it["rarity"]]["name"]])
        if it.get("slot"):
            facts.append(["Slot", SLOT_NAMES.get(it["slot"], it["slot"]).rstrip("s")])
        if it.get("weaponType"):
            facts.append(["Weapon type", self.weapons[it["weaponType"]]["name"]])
        if it.get("requires"):
            facts.append(["Required level", it["requires"]["level"]])
        if it.get("stats"):
            facts.append(["Stats", stats_text(it["stats"])])
        if it.get("upgradeSlots"):
            facts.append(["Upgrade slots", it["upgradeSlots"]])
        if it.get("targets"):
            names = [self.weapons[t]["name"] if t in self.weapons else SLOT_NAMES.get(t, t) for t in it["targets"]]
            facts.append(["Used on", ", ".join(names)])
        if it.get("bonus"):
            facts.append(["Bonus", stats_text(it["bonus"])])
        for e in it.get("effects", []):
            facts.append(["Effect", self.effect(e)])
        if it.get("chair"):
            facts.append(["Effect", "Sit to recover faster"])
        facts.append(["Sells for", f"{num(it['price'])} mesos" if it["price"] and it["kind"] != "quest" else "Cannot be sold"])
        b.append(table(["", ""], facts))
        if self.item_sources.get(iid):
            b.append("## How to get\n")
            b += [f"- {s}" for s in dict.fromkeys(self.item_sources[iid])]
            b.append("")
        if self.item_uses.get(iid):
            b.append("## Used for\n")
            b += [f"- {s}" for s in dict.fromkeys(self.item_uses[iid])]
            b.append("")
        return "\n".join(b)

    def effect(self, e):
        t = e["type"]
        if t == "heal":
            parts = []
            for k, label in (("hp", "HP"), ("mp", "MP")):
                if k in e:
                    parts.append(f"{e[k]} {label}")
                if k + "Percent" in e:
                    parts.append(f"{e[k + 'Percent']}% {label}")
            return "Restores " + " and ".join(parts)
        if t == "buff":
            return f"{stats_text(e['stats'])} for {seconds(e['durationMs'])}"
        if t == "cure":
            return "Cures " + ", ".join(e["status"])
        if t == "exp":
            return f"Gives {num(e['amount'])} EXP"
        if t == "returnTown":
            return "Returns you to town"
        if t == "resetSp":
            return "Resets your skill points"
        if t == "resetAp":
            return f"Moves an ability point from {e['from'].upper()} to {e['to'].upper()}"
        if t == "extendTab":
            return f"Adds slots to the {e['tab'].upper()} inventory tab"
        return t

    # ------------------------------------------------------------ skills

    def gen_skills(self):
        book_titles = {}
        for jid, j in self.jobs.items():
            book_titles[j["skills"]] = f"{j['name']} Skills"
        book_titles.update({"buffs": "Buff Skills", "passives": "Passive Skills", "tutors": "Taught Skills"})

        order = [self.jobs[j]["skills"] for j in self.job_order] + [b for b in ("buffs", "tutors", "passives") if b in self.books]
        order += [b for b in self.books if b not in order]
        idx = ["# Skills\n", "Skill numbers come from formulas of the skill level; each table below works them out level by level.\n"]
        rows = []
        for book in order:
            title = book_titles.get(book, book.replace("_", " ").title())
            self.write(f"skills/{book}.md", self.skill_book_page(book, title))
            for sid, s in self.books[book].items():
                rows.append([self.skill(sid), title.replace(" Skills", ""), s["kind"].title(), s["max"], self.text(s["description"])])
        idx.append(table(["Skill", "Group", "Kind", "Max level", "Description"], rows))
        self.write("skills/index.md", "\n".join(idx))
        self.nav["Skills"] = ["skills/index.md"] + [f"skills/{b}.md" for b in order]

    def skill_book_page(self, book, title):
        b = [f"# {title}\n"]
        jobs = [jid for jid, j in self.jobs.items() if j["skills"] == book]
        if jobs:
            b.append(f"Learned with skill points by the {self.job(jobs[0])}.\n")
