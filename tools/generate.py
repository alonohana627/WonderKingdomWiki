    def map_page(self, mid, m):
        b = [f"# {m['name']}\n"]
        facts = [["Region", self.region(m["region"])], ["Kind", m["purpose"].title()]]
        if m.get("difficulty"):
            facts.append(["Level", m["difficulty"]])
        if m.get("returnTown"):
            facts.append(["Return town", self.town(m["returnTown"])])
        b.append(table(["", ""], facts))
        exits = [p for p in m.get("portals", []) if p.get("to")]
        if exits:
            b.append("## Exits\n")
            b += [f"- {self.map(p['to'])}" for p in exits]
            b.append("")
        npcs = [a["name"] for a in m.get("actors", []) if a["name"] in self.npcs]
        if npcs:
            b.append("## NPCs\n")
            b += [f"- {self.npc(n)}{' (' + self.npcs[n]['title'] + ')' if self.npcs[n].get('title') else ''}" for n in npcs]
            b.append("")
        counts = defaultdict(int)
        for s in m.get("spawns", []):
            counts[s["mob"]] += s.get("count", 1)
        if counts:
            b.append("## Monsters\n")
            b.append(table(["Monster", "Level", "Number"], [[self.mob(x), self.mobs[x]["level"] if x in self.mobs else "-", c] for x, c in counts.items()]))
        nodes = defaultdict(int)
        for n in m.get("nodes", []):
            nodes[n["node"]] += 1
        if nodes:
            b.append("## Gathering\n")
            b.append(table(["Node", "Profession", "Gives", "Number"], [
                [self.nodes[n]["name"], self.profession(self.nodes[n]["profession"]), self.item(self.nodes[n]["item"]), c]
                for n, c in nodes.items() if n in self.nodes]))
        found = [(did, x) for did, x in self.discoveries["discoveries"].items() if x.get("trigger", {}).get("map") == mid]
        if found:
            b.append("## Discoveries\n")
            b += [f"- [{x['name']}](../world/discoveries.md#{anchor(did)})" for did, x in found]
            b.append("")
        bosses = [bid for bid, bo in self.bosses.items() if bo["arena"] == mid]
        runs = [rid for rid, r in self.runs.items() if any(s["map"] == mid for s in r["stages"])]
        if bosses or runs:
            b.append("## Encounters\n")
            b += [f"- {self.boss(x)}" for x in bosses] + [f"- {self.run(x)}" for x in runs]
            b.append("")
        return "\n".join(b)

