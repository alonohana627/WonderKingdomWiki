    def gen_runs(self):
        idx = ["# Runs\n", "Runs are staged challenges entered through an NPC.\n"]
        idx.append(table(["Run", "Stages"], [[self.run(r), len(self.runs[r]["stages"])] for r in self.run_order]))
        self.write("runs/index.md", "\n".join(idx))
        for rid in self.run_order:
            r = self.runs[rid]
            b = [f"# {r['name']}\n", f"*{self.text(r['description'])}*\n"]
            if r.get("onDeath") == "fail":
                b.append("Dying ends the run.\n")
            for i, s in enumerate(r["stages"]):
                b.append(f"## {i + 1}. {s['name']}\n")
                b.append(f"Map: {self.map(s['map'])}" + (f". Time limit: {s['timeLimitSeconds']} s." if s.get("timeLimitSeconds") else "") + "\n")
                b += [f"- {self.run_objective(r, o)}" for o in s.get("objectives", [])]
                b.append("")
                for w, wave in enumerate(s.get("waves", [])):
                    b.append(f"Wave {w + 1}: " + ", ".join(f"{m['count']} {self.mob(m['mob'])}" for m in wave["mobs"]) + "\n")
            for mode in r.get("modes", []):
                b.append(f"## Rewards ({mode['name']})\n")
                if mode.get("firstRewards"):
                    b.append("First clear: " + ", ".join(self.rewards(mode["firstRewards"])) + "\n")
                if mode.get("rewards"):
                    b.append("Every clear: " + ", ".join(self.rewards(mode["rewards"])) + "\n")
            self.write(f"runs/{rid}.md", "\n".join(b))
        self.nav["Runs"] = ["runs/index.md"] + [f"runs/{r}.md" for r in self.run_order]

    def run_objective(self, r, o):
        if o.get("text"):
            return o["text"]
        if o["kind"] == "collect":
            name = r.get("items", {}).get(o["item"], {}).get("name") or self.item(o["item"])
            return f"Collect {o['count']} {name}s"
        if o["kind"] == "reach":
            return f"Reach {o.get('name', 'the goal')}"
        if o["kind"] == "survive":
            return f"Survive for {o['seconds']} seconds"
        return o["kind"]

