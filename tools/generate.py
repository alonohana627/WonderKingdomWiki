    def condition(self, text):
        m = re.fullmatch(r"standing (npc|town) (\w+) >= (\w+)", text.strip())
        if m:
            who = self.npc(m.group(2)) if m.group(1) == "npc" else self.town_name(m.group(2))
            return f"{m.group(3)} standing with {who}"
        m = re.fullmatch(r"standing honor >= (.+)", text.strip())
        if m:
            return f"[Honor](../systems/honor.md) rank {m.group(1)}"
        return f"`{text}`"

    def objective(self, o):
        k = o["kind"]
        if k == "hunt":
            mobs = o.get("mob") or []
            mobs = mobs if isinstance(mobs, list) else [mobs]
            rank = {"elite": "Elite ", "epic": "Epic "}.get(o.get("rank"), "")
            where = f" in {self.map(o['map'])}" if o.get("map") else ""
            if o.get("name"):
                what = f"{o['name']}{'s' if o['count'] > 1 else ''}" + (f" ({', '.join(self.mob(m) for m in mobs)})" if mobs else "")
            elif mobs:
                what = ", ".join(self.mob(m) for m in mobs)
            else:
                what = "monsters"
            return f"Defeat {o['count']} {rank}{what}{where}"
        if k == "collect":
            return f"Bring {o['count']} {self.item(o['item'])}" + (" (taken)" if o.get("taken") else "")
        if k == "deliver":
            return f"Deliver {o['count']} {self.item(o['item'])}"
        if k == "gather":
            return f"Gather {o['count']} {self.item(o['item'])}"
        if k == "make":
            return f"Make {o['count']} {self.item(o['item'])}"
        if k == "use":
            what = self.skill(o["skill"]) if o.get("skill") else self.item(o["item"])
            return f"Use {what} {o['count']} times" if o["count"] > 1 else f"Use {what}"
        if k == "reach":
            return f"Reach {o['name'] + ' in ' if o.get('name') else ''}{self.map(o['map'])}"
        if k == "inspect":
            return f"Look at {o.get('name') or 'the spot'} in {self.map(o['map'])}"
        if k == "talk":
            return f"Talk to {self.npc(o['npc'])}"
        if k == "level":
            return f"Reach level {o['level']}"
        if k == "clear":
            what = self.encounter(o["encounter"])
            mode = f" on {o['mode'].title()}" if o.get("mode") else ""
            times = f" {o['count']} times" if o.get("count", 1) > 1 else ""
            return f"Clear {what}{mode}{times}"
        if k == "study":
            return f"Defeat every kind of monster in {self.region(o['region'])}"
        if k == "discover":
            d = self.discoveries["discoveries"].get(o["discovery"], {})
            return f"Discover [{d.get('name', o['discovery'])}](../world/discoveries.md#{anchor(o['discovery'])})"
        return k

