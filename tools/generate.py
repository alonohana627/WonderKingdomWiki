        b.append(" | ".join(links) + "\n")

        maps = self.owned("maps", t)
        areas = defaultdict(list)
        for m in maps:
            areas[self.map_area(m)].append(m)
        b.append("## Maps\n")
        b.append("Maps are grouped by the part of the town's lands they belong to. Levels are those of the monsters and bosses there; "
                 "difficulty is the map's own rating of how dangerous it is.\n")
