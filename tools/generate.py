            cat = "Story" if any(self.quests[q].get("category") == "story" for q in line) else first.get("category", "side").title()
            b.append(f"## {first['title']}\n")
            levels = [self.quests[q].get("requires", {}).get("level", 1) for q in line]
            b.append(f"*{cat} line, {len(line)} quest{'s' if len(line) > 1 else ''}, from level {min(levels)}. Starts with {self.npc(first['giver'])}.*\n")
