def _town_order() -> list[str]:
    """Game town ids in the order of the Towns table on the lore's Veligor page."""
    page = DOCS / "lore" / "veligor.md"
    if not page.exists():
        return []
    text = page.read_text(encoding="utf-8").split("## Towns", 1)[-1]
    return [t.replace("-", "_") for t in re.findall(r"\(towns/([a-z-]+)\.md\)", text)]


TOWN_ORDER = _town_order()

