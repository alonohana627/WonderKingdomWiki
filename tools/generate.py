    def profession_page(self, x):
        b = [f"# {x['name']}\n", f"*{x['description']}*\n"]
        e = x["exp"]
        b.append("## EXP per level\n")
        b.append(f"EXP to the next level is `{e['base']} + {e['square']} * (L-1)^2 + {e['cube']} * (L-1)^3` at level L.\n")
        rows, total = [], 0
        for lv in range(1, self.professions["maxLevel"]):
            need = e["base"] + e["square"] * (lv - 1) ** 2 + e["cube"] * (lv - 1) ** 3
            if lv <= 20 or lv % 10 == 0:
                rows.append([lv, num(need), num(total)])
            total += need
        b.append(table(["Level", "EXP to next", "Total EXP to reach"], rows))
        if x.get("perks"):
            b.append("## Perks\n")
            b.append(table(["Level", "Perk", "Effect"], [[k["level"], k["name"], k["text"]] for k in x["perks"]]))
        nodes = {nid: n for nid, n in self.nodes.items() if n["profession"] == x["id"]}
        if nodes:
            b.append("## Nodes\n")
            b.append(table(["Node", "Level", "Gives", "Yield", "EXP", "Regrows", "Found in"], [
                [n["name"], n["level"], self.item(n["item"]), f"{n['yield'][0]}-{n['yield'][1]}", n["exp"],
                 seconds(n["replenishSeconds"] * 1000), ", ".join(self.map(m) for m in self.node_maps.get(nid, [])) or "-"]
                for nid, n in nodes.items()]))
        recipes = self.recipes.get(x["id"], {})
        if recipes:
            b.append("## Recipes\n")
            rows = []
            for rid, r in sorted(recipes.items(), key=lambda kv: kv[1]["level"]):
                out = r["output"]
                note = []
                if r.get("reward"):
                    note.append("learned from a quest")
                if r.get("double"):
                    note.append("can make double")
                if r.get("critical"):
                    note.append(f"can come out {self.rarities[r['critical']]['name']}")
                rows.append([r["level"], f"{self.item(out['item'])}{' x' + str(out['count']) if out['count'] > 1 else ''}",
                             ", ".join(f"{self.item(i['item'])} x{i['count']}" for i in r["inputs"]), r["exp"], "; ".join(note)])
            b.append(table(["Level", "Makes", "Needs", "EXP", "Notes"], rows))
        return "\n".join(b)

