    def skill_levels(self, s):
        columns = []  # (header, formula)
        for k, f in s.get("levels", {}).items():
            if k not in SKILL_COLUMNS:
                continue
            columns.append((SKILL_COLUMNS.get(k, k), f, k == "durationMs"))
        gives = s.get("gives", {})
        for k, f in gives.get("stats", {}).items():
            columns.append((STAT_NAMES.get(k, k), f, False))
        for k, f in gives.get("percent", {}).items():
            columns.append((f"{STAT_NAMES.get(k, k)} %", f, False))
        if not columns:
            return ""
        rows = []
        for x in range(1, s["max"] + 1):
            row = [x]
            for _, f, is_ms in columns:
                v = eval_formula(f, x)
                row.append(f"{v / 1000:g}" if is_ms else num(v))
            rows.append(row)
        formulas = ", ".join(f"{h} = `{f}`" for h, f, _ in columns)
        return table(["Level"] + [h for h, _, _ in columns], rows) + f"\nFormulas (x is the skill level, division rounds down): {formulas}\n"

