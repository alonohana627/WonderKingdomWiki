    def quest_lines(self, qids):
        """Quests grouped into lines (chains joined by "requires" quests), each in the order it is played."""
        qset = set(qids)
        parent = {q: q for q in qids}

        def root(q):
            while parent[q] != q:
                parent[q] = parent[parent[q]]
                q = parent[q]
            return q

        for q in qids:
            for r in self.quests[q].get("requires", {}).get("quests", []):
                if r in qset:
                    parent[root(q)] = root(r)
        groups = defaultdict(list)
        for q in qids:
            groups[root(q)].append(q)
        key = lambda q: (self.quests[q].get("sort", 0), q)
        lines = []
        for members in groups.values():
            done, order = set(), []
            pending = sorted(members, key=key)
            while pending:
                ready = [q for q in pending if all(r in done or r not in qset for r in self.quests[q].get("requires", {}).get("quests", []))]
                q = (ready or pending)[0]
                order.append(q)
                done.add(q)
                pending.remove(q)
            lines.append(order)
        story = lambda line: 0 if any(self.quests[q].get("category") == "story" for q in line) else (2 if all(self.quests[q].get("category") == "repeatable" for q in line) else 1)
        lines.sort(key=lambda line: (story(line), min(key(q) for q in line)))
        return lines

