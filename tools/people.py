"""Check the NPC registry in data/people/ and render docs/lore/people/.

    python tools/people.py            check, then write the pages
    python tools/people.py --check    check only, and fail if the pages are stale

The registry is the source of truth for who lives where. Every check below
exists to stop two pages from contradicting each other: one holder per office,
one spouse per person, relationships written once with both directions, and
cross-town ties only where data/people/kingdom.yml allows them.
"""

from __future__ import annotations

import argparse
import re
import shutil
import sys
from collections import Counter, defaultdict
from pathlib import Path

import yaml

WIKI = Path(__file__).resolve().parent.parent
DATA = WIKI / "data" / "people"
OUT = WIKI / "docs" / "lore" / "people"
LORE = DATA / "lore"
MIN_LORE_WORDS = 400
GAME_CONTENT = WIKI.parent / "GameLib" / "games" / "wonder_kingdom" / "content"
GAME_PAGES = WIKI / "docs" / "npcs"  # the game's NPC pages, written by tools/generate.py

ROLES = {
    "ruler": "Ruler", "council": "Council", "official": "Official", "guard": "Guard",
    "merchant": "Merchant", "craftsman": "Craftsman", "service": "Service", "worker": "Worker",
    "scholar": "Scholar", "healer": "Healer", "performer": "Performer", "adventurer": "Adventurer",
    "resident": "Resident", "child": "Child", "animal": "Animal",
}
AGES = {"child", "young", "adult", "elder"}
REQUIRED = ["id", "name", "title", "role", "place", "age", "personality", "story"]
OPTIONAL = ["office", "game", "sells", "kind", "family", "menu"]
SPOUSE = re.compile(r"\b(wife|husband|spouse)\b", re.I)
PARENT = re.compile(r"^(father|mother)$", re.I)
HEADER = "<!-- Generated by tools/people.py from data/people/. Do not edit: changes are overwritten. -->\n\n"


def load(path):
    with path.open(encoding="utf-8") as f:
        return yaml.safe_load(f)


class Registry:
    def __init__(self):
        self.errors: list[str] = []
        self.kingdom = load(DATA / "kingdom.yml")
        self.towns = self.kingdom["towns"]
        self.npcs: dict[str, dict] = {}
        self.rels = defaultdict(list)  # npc id -> [(other id, what other is to npc)]
        for town in self.towns:
            path = DATA / f"{town}.yml"
            if not path.exists():
                self.err(f"{town}: missing {path.name}")
                continue
            data = load(path) or {}
            self.read_town(town, data)
        self.read_links()
        self.check_offices()
        self.check_family_ties()
        self.check_game()
        self.read_lore()

    def read_lore(self):
        """data/people/lore/<town>/<id>.md: the long lore of every NPC who is not a menu NPC."""
        self.lore: dict[str, str] = {}
        missing = []
        for nid, n in self.npcs.items():
            path = LORE / n["town"] / f"{nid}.md"
            if n.get("menu"):
                if path.exists():
                    self.err(f"{nid}: menu NPCs have no lore file ({path.relative_to(WIKI).as_posix()})")
                continue
            if not path.exists():
                missing.append(nid)
                continue
            text = path.read_text(encoding="utf-8").strip()
            words = len(re.findall(r"[A-Za-z0-9'’-]+", text))
            if words < MIN_LORE_WORDS:
                self.err(f"{nid}: lore has {words} words, needs at least {MIN_LORE_WORDS}")
            if re.search(r"^#{1,2} ", text, re.M):
                self.err(f"{nid}: lore may only use ### headings or none")
            self.lore[nid] = text
        if LORE.exists():
            for path in LORE.rglob("*.md"):
                if path.stem not in self.npcs or path.parent.name != self.npcs[path.stem]["town"]:
                    self.err(f"{path.relative_to(WIKI).as_posix()}: no NPC {path.stem} in {path.parent.name}")
        if missing:
            self.err(f"{len(missing)} NPCs still need lore, for example {', '.join(missing[:5])}")

    def err(self, msg):
        self.errors.append(msg)

    def read_town(self, town, data):
        town_npcs = data.get("npcs") or []
        places = set(self.towns[town]["places"])
        if len(town_npcs) != self.towns[town]["count"]:
            self.err(f"{town}: {len(town_npcs)} NPCs, expected {self.towns[town]['count']}")
        for n in town_npcs:
            nid = n.get("id", "?")
            for field in REQUIRED:
                if not n.get(field):
                    self.err(f"{town}/{nid}: missing {field}")
            for field in n:
                if field not in REQUIRED + OPTIONAL:
                    self.err(f"{town}/{nid}: unknown field {field}")
            if not re.fullmatch(r"[a-z][a-z0-9_]*", str(nid)):
                self.err(f"{town}/{nid}: id must be lower_snake_case")
            if nid in self.npcs:
                self.err(f"{town}/{nid}: id already used in {self.npcs[nid]['town']}")
            if n.get("role") not in ROLES:
                self.err(f"{town}/{nid}: role {n.get('role')!r} is not one of {sorted(ROLES)}")
            if n.get("age") not in AGES:
                self.err(f"{town}/{nid}: age {n.get('age')!r} is not one of {sorted(AGES)}")
            if n.get("place") not in places:
                self.err(f"{town}/{nid}: place {n.get('place')!r} is not one of {sorted(places)}")
            if town == "midbarium" and n.get("role") != "animal" and n.get("family") not in ("Kragvar", "Tolmach", "Uskari", "Brenna", "none"):
                self.err(f"{town}/{nid}: family must be Kragvar, Tolmach, Uskari, Brenna or none")
            self.npcs[nid] = {**n, "town": town}
        for r in data.get("relationships") or []:
            self.add_rel(r, town)

    def add_rel(self, r, town):
        if not (isinstance(r, list) and len(r) == 4 and all(isinstance(x, str) and x for x in r)):
            self.err(f"{town}: relationship {r!r} must be [a, b, what a is to b, what b is to a]")
            return
        a, b, a_to_b, b_to_a = r
        for x in (a, b):
            if x not in self.npcs:
                self.err(f"{town}: relationship {a}-{b}: unknown NPC {x}")
                return
        if a == b:
            self.err(f"{town}: {a} is related to themself")
            return
        if town is not None and (self.npcs[a]["town"] != town or self.npcs[b]["town"] != town):
            self.err(f"{town}: {a}-{b} crosses towns; cross-town ties go in kingdom.yml links")
            return
        if any(o == b for o, _ in self.rels[a]):
            self.err(f"{a}-{b}: the pair is listed twice")
            return
        self.rels[a].append((b, b_to_a))  # b is <b_to_a> to a
        self.rels[b].append((a, a_to_b))

    def read_links(self):
        for r in self.kingdom.get("links") or []:
            self.add_rel(r, None)

    def check_offices(self):
        held = Counter(n.get("office") for n in self.npcs.values() if n.get("office"))
        for office, count in held.items():
            if office not in self.kingdom["offices"]:
                self.err(f"office {office} is not in kingdom.yml")
            elif count > 1:
                self.err(f"office {office} is held by {count} NPCs")
        for office, o in self.kingdom["offices"].items():
            n = self.npcs.get(o["npc"])
            if n is None:
                self.err(f"office {office}: {o['npc']} is not in {o['town']}.yml")
                continue
            if n.get("office") != office or n["town"] != o["town"] or n["name"] != o["name"] or n["title"] != o["title"]:
                self.err(f"office {office}: {o['npc']} must have office {office}, name {o['name']!r}, title {o['title']!r} in {o['town']}.yml")
        rulers = [i for i, n in self.npcs.items() if n.get("role") == "ruler" and not n.get("office")]
        for i in rulers:
            self.err(f"{i}: role ruler needs an office from kingdom.yml")

    def check_family_ties(self):
        names = Counter(n["name"] for n in self.npcs.values() if n.get("name"))
        for name, c in names.items():
            if c > 1:
                who = [f"{i} ({n['town']})" for i, n in self.npcs.items() if n["name"] == name]
                self.err(f"name {name!r} is used {c} times: {', '.join(who)}")
        for nid, rel in self.rels.items():
            spouses = [o for o, what in rel if SPOUSE.search(what)]
            if len(spouses) > 1:
                self.err(f"{nid} has {len(spouses)} spouses: {', '.join(spouses)}")
            for parent in ("father", "mother"):
                ps = [o for o, what in rel if what.lower() == parent]
                if len(ps) > 1:
                    self.err(f"{nid} has {len(ps)} {parent}s: {', '.join(ps)}")

    def check_game(self):
        """An NPC that is in the game (its id, or its "game" id) must have the game's name and title."""
        if not GAME_CONTENT.exists():
            return
        files = {p.stem: p for p in GAME_CONTENT.glob("npcs/*.json")}
        files.update({p.stem: p for p in GAME_CONTENT.glob("towns/*/npcs/*.json")})
        for nid, n in self.npcs.items():
            g = n.get("game") or nid
            path = files.get(g)
            if path is None:
                if n.get("game"):
                    self.err(f"{nid}: game NPC {g} does not exist")
                continue
            game = yaml.safe_load(path.read_text(encoding="utf-8"))
            if game.get("title") and game["title"] != n["title"]:
                self.err(f"{nid}: title {n['title']!r} differs from the game's {game['title']!r}")
            if game.get("name") != n["name"]:
                self.err(f"{nid}: name {n['name']!r} differs from the game's {game.get('name')!r}")

    # ------------------------------------------------------------ pages
    # people/index.md, people/<town>/index.md (a Name | Role table) and
    # people/<town>/<id>.md, one page per NPC. A menu NPC (a shop, storage or
    # taxi with no story of its own) gets a short page without personality or story.

    def link(self, nid, from_dir):
        """A link to an NPC's page from a page in people/<from_dir>/ (None: people/ itself)."""
        n = self.npcs[nid]
        if from_dir is None:
            target = f"{n['town']}/{nid}.md"
        elif from_dir == n["town"]:
            target = f"{nid}.md"
        else:
            target = f"../{n['town']}/{nid}.md"
        return f"[{n['name']}]({target})"

    def town_page(self, town):
        t = self.towns[town]
        people = [i for i, n in self.npcs.items() if n["town"] == town]
        people.sort(key=lambda i: (not self.npcs[i].get("office"), bool(self.npcs[i].get("menu"))))
        lines = [f"# People of {t['name']}\n",
                 f"The {len(people)} people of [{t['name']}](../../towns/{town}.md) in the game's first release.\n",
                 "| Name | Role |", "|---|---|"]
        lines += [f"| {self.link(i, town)} | {self.npcs[i]['title']} |" for i in people]
        return HEADER + "\n".join(lines) + "\n"

    def npc_page(self, nid):
        n = self.npcs[nid]
        town = n["town"]
        out = [f"# {n['name']}\n", f"*{n['title']}*\n"]
        facts = [["Town", f"[{self.towns[town]['name']}](../../towns/{town}.md)"], ["Where", n["place"]]]
        if not n.get("menu"):
            facts.append(["Role", ROLES[n["role"]]])
            if n.get("kind") != "Child of the Tree":  # their age is an open question
                facts.append(["Age", n["age"].title()])
            if n.get("family"):
                facts.append(["Family", n["family"]])
            if n.get("kind"):
                facts.append(["Kind", n["kind"]])
        if n.get("sells"):
            facts.append(["Sells", n["sells"]])
        game = n.get("game") or nid
        if (GAME_PAGES / f"{game}.md").exists():
            facts.append(["In the game", f"[{n['name']}](../../../npcs/{game}.md)"])
        out += ["|  |  |", "|---|---|"] + [f"| {a} | {b} |" for a, b in facts] + [""]
        if not n.get("menu"):
            out += ["## Personality\n", f"{n['personality'].strip()}\n"]
            lore = self.lore.get(nid)
            out += ["## Lore\n", f"{lore}\n"] if lore else ["## Story\n", f"{n['story'].strip()}\n"]
        rel = self.rels.get(nid)
        if rel:
            out.append("## Relationships\n")
            out += [f"- {self.link(o, town)}: {what}" for o, what in rel]
            out.append("")
        return HEADER + "\n".join(out).rstrip() + "\n"

    def index_page(self):
        lines = ["# People\n", "Everyone in Wonder Kingdom's first release, town by town.\n",
                 "| Town | People |", "|---|---|"]
        for town, t in self.towns.items():
            lines.append(f"| [{t['name']}]({town}/index.md) | {sum(1 for n in self.npcs.values() if n['town'] == town)} |")
        lines += ["", "## Who leads where\n", "| Town | Leader | Title |", "|---|---|---|"]
        for office, o in self.kingdom["offices"].items():
            if o["npc"] in self.npcs:
                lines.append(f"| {self.towns[o['town']]['name']} | {self.link(o['npc'], None)} | {o['title']} |")
        return HEADER + "\n".join(lines).rstrip() + "\n"

    def pages(self):
        files = {"index.md": self.index_page()}
        for town in self.towns:
            files[f"{town}/index.md"] = self.town_page(town)
        for nid, n in self.npcs.items():
            files[f"{n['town']}/{nid}.md"] = self.npc_page(nid)
        return files


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="check only, and fail if the pages are stale")
    args = parser.parse_args()
    reg = Registry()
    if reg.errors:
        print(f"{len(reg.errors)} problems:")
        for e in reg.errors:
            print(f"  {e}")
        sys.exit(1)
    pages = reg.pages()
    if args.check:
        on_disk = {f.relative_to(OUT).as_posix() for f in OUT.rglob("*.md")} if OUT.exists() else set()
        stale = sorted(on_disk ^ set(pages)) + [name for name, text in pages.items()
                                                if (OUT / name).exists() and (OUT / name).read_text(encoding="utf-8") != text]
        if stale:
            print("Stale pages, run python tools/people.py: " + ", ".join(stale[:10]))
            sys.exit(1)
        print(f"{len(reg.npcs)} NPCs, no problems")
        return
    shutil.rmtree(OUT, ignore_errors=True)
    for name, text in pages.items():
        (OUT / name).parent.mkdir(parents=True, exist_ok=True)
        (OUT / name).write_text(text, encoding="utf-8", newline="\n")
    print(f"{len(reg.npcs)} NPCs, no problems; wrote {len(pages)} pages")


if __name__ == "__main__":
    main()
